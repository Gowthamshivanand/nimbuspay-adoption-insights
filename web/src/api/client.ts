/* Static demo (GitHub Pages): built with VITE_STATIC=1 only. Off by default, so the normal build talks to the backend exactly as before.
   Answers come from dist/static-api/index.json, generated by tools/build_static_api.py from the 874 responses recorded from the real
   backend (parity/golden/golden_api.json). A request with no recording gets a polite "Live in the full app" state; nothing is invented. */
export const STATIC = import.meta.env.VITE_STATIC === "1";
const BASE = import.meta.env.BASE_URL;
export const LIVE_MSG = "Live in the full app. This static demo replays recorded responses from the real engine, and this request was not recorded";
type Rec = { s: number; j: unknown };
type Sse = { meta: { event: string; data: unknown }; tokens: string; n_tokens: number; done: { event: string; data: unknown } };
type StaticIdx = { scenarios: string[]; json: Record<string, Rec>; sse: Record<string, Sse> };
let staticIdx: Promise<StaticIdx> | null = null;
let staticScen = "baseline";   // the dataset the recordings were made on; switches on a recorded /api/load/<key>
const loadIdx = () => (staticIdx ??= fetch(BASE + "static-api/index.json").then((r) => r.json()));
const sortKeys = (x: unknown): unknown => Array.isArray(x) ? x.map(sortKeys)
  : x && typeof x === "object" ? Object.fromEntries(Object.keys(x).sort().map((k) => [k, sortKeys((x as Record<string, unknown>)[k])])) : x;
/* Same rules as tools/build_static_api.py canon(): drop nulls and session_id; what-if drops connector_fix=false;
   cost fills the server's own defaults (the backend does the same for missing fields), so the default form matches the recorded default. */
async function staticKey(method: string, path: string, body: Record<string, unknown> | undefined) {
  let b: Record<string, unknown> = Object.fromEntries(Object.entries(body || {}).filter(([k, v]) => v !== null && v !== undefined && k !== "session_id"));
  if (path === "/api/whatif" && b.connector_fix === false) delete b.connector_fix;
  if (path === "/api/cost" && method === "POST") {
    const meta = (await loadIdx()).json["*|GET /api/cost|{}"];
    b = { ...((meta?.j as { defaults?: Record<string, unknown> })?.defaults || {}), ...b };
  }
  return method + " " + path + "|" + JSON.stringify(sortKeys(b));
}
async function staticFind<K extends "json" | "sse">(kind: K, method: string, path: string, body?: Record<string, unknown>): Promise<StaticIdx[K][string] | undefined> {
  const I = await loadIdx(), k = await staticKey(method, path, body);
  return (I[kind][staticScen + "|" + k] ?? I[kind]["*|" + k]) as StaticIdx[K][string] | undefined;
}
async function staticRequest<R>(path: string, opts?: RequestInit): Promise<R> {
  const method = (opts?.method || "GET").toUpperCase();
  const body = typeof opts?.body === "string" ? JSON.parse(opts.body) : undefined;
  const hit = opts?.body !== undefined && typeof opts.body !== "string" ? undefined : await staticFind("json", method, path, body);   // file uploads: never recorded for arbitrary files
  if (!hit) {
    if (method === "POST" && path === "/api/ask") {   // a polite, clearly labelled state in the chat, not an answer and not a number
      const st = (await staticFind("json", "GET", "/api/state"))?.j as { data_as_of?: string } | undefined;
      return { type: "caveat", intent: "static_demo", mode: "static demo", brain: "rules", citations: [], data_as_of: st?.data_as_of, label: "Synthetic data",
        text: LIVE_MSG + " for this question and role. Pick one of the suggested questions to see a recorded answer from the real engine." } as R;
    }
    throw new Error(LIVE_MSG + ".");
  }
  if (hit.s >= 400) { const d = (hit.j as { detail?: unknown })?.detail; throw new Error((d as string) || "Error " + hit.s); }
  const m = /^\/api\/load\/([a-z]+)$/.exec(path); if (m) staticScen = m[1];
  return hit.j as R;
}
function staticStream(body: Record<string, unknown>): Promise<Response> {
  return staticFind("sse", "POST", "/api/ask/stream", body).then((rec) => {
    if (!rec) return new Response(null, { status: 404 });   // the caller falls back to /api/ask (recorded answer or the "live in full app" state)
    const enc = new TextEncoder(), ev = (e: string, d: unknown) => enc.encode(`event: ${e}\ndata: ${JSON.stringify(d)}\n\n`);
    const toks = rec.tokens.match(/\S+\s*/g) || [];        // replay the recorded text as the stream, word by word
    return new Response(new ReadableStream({
      async start(c) {
        c.enqueue(ev("meta", rec.meta.data));
        for (const t of toks) { c.enqueue(ev("token", t)); await new Promise((r) => setTimeout(r, 18)); }
        c.enqueue(ev("done", rec.done.data)); c.close();
      },
    }), { status: 200, headers: { "Content-Type": "text/event-stream" } });
  });
}

export async function request<R = unknown>(path: string, opts?: RequestInit): Promise<R> {
  if (STATIC) return staticRequest<R>(path, opts);
  const r = await fetch(path, opts);
  if (!r.ok) throw new Error((await r.json().catch(() => ({}))).detail || r.statusText);
  return r.json();
}
const post = <R>(path: string, body?: unknown) =>
  request<R>(path, body === undefined ? { method: "POST" } : { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
const postForm = <R>(path: string, form: FormData) => request<R>(path, { method: "POST", body: form });

